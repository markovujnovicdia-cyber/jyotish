#!/usr/bin/env python3
"""Regenerate deterministic transit rows from the unchanged Python oracle.

Run with the project's Python dependencies installed. --check compares the
complete generated JSON bytes without modifying a resource during a Swift build.
"""
from argparse import ArgumentParser
from pathlib import Path
import json
import random
import shutil
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "Packages/JyotishCore/Tests/JyotishCoreTests/Fixtures/TransitReference.json"
PLANETS = ["Sunce", "Mjesec", "Mars", "Merkur", "Jupiter", "Venera", "Saturn", "Rahu", "Ketu"]


def generate():
    sys.path.insert(0, str(ROOT / "OriginalPython"))
    import swisseph as swe
    from core import transits
    from core.constants import RASHI
    from core.ephemeris import PlanetPosition

    if swe.version != "2.10.03":
        raise SystemExit(f"Expected Swiss Ephemeris 2.10.03, found {swe.version}")
    bundled = ROOT / "Packages/JyotishCore/Sources/JyotishCore/Resources/Ephemeris"
    # Python's Swiss library has the same 242-byte resource-path limit as the
    # native adapter. Use byte-identical files under a short temporary path.
    with tempfile.TemporaryDirectory(prefix="jy-transit-oracle-") as temporary:
        if len(temporary.encode("utf-8")) > 242:
            raise SystemExit("Temporary ephemeris path exceeds Swiss's 242-byte limit")
        for name in ("sepl_18.se1", "semo_18.se1"):
            shutil.copyfile(bundled / name, Path(temporary) / name)
        swe.set_ephe_path(temporary)
        flags = swe.FLG_SWIEPH | swe.FLG_SIDEREAL | swe.FLG_SPEED
        if not swe.calc_ut(2451545, swe.MOON, flags)[1] & swe.FLG_SWIEPH:
            raise SystemExit("Swiss data files were not used; refusing to generate Moshier references")

        random_source = random.Random(20261102)
        cases = []
        original_positions = transits.get_planet_positions

        def record(jd, ascendant, moon, positions):
            expected = transits.compute_transits(jd, ascendant, moon)
            return {
                "jd": jd, "ascendant": ascendant, "moon": moon,
                # The transit formula consumes the retrograde flag only, not
                # the speed magnitude; +/-1 preserves that exact input.
                "positions": {name: {"longitude": value.longitude,
                                      "speed": -1 if value.is_retrograde else 1}
                              for name, value in positions.items()},
                "expected": {name: vars(value) for name, value in expected.items()},
            }

        for index in range(60):
            jd = 2451545 + index * 14.34
            positions = original_positions(jd)
            ascendant = random_source.uniform(-720, 720)
            moon = random_source.uniform(-720, 720)
            cases.append(record(jd, ascendant, moon, positions))

        # Inject synthetic positions into the original function for exact sign
        # boundaries. This changes no Python file or formula and is restored.
        boundaries = [(359.999999, 0), (0, 359.999999), (-30, 360), (360, 720), (30, 30)]
        try:
            for index, (ascendant, moon) in enumerate(boundaries):
                positions = {}
                for order, name in enumerate(PLANETS):
                    longitude = (index * 30 + order * 30) % 360
                    sign = int(longitude // 30)
                    positions[name] = PlanetPosition(name, longitude, sign, RASHI[sign],
                                                     longitude % 30, order % 2 == 0)
                transits.get_planet_positions = lambda jd, fixed=positions: fixed
                cases.append(record(2451545, ascendant, moon, positions))
        finally:
            transits.get_planet_positions = original_positions

    return {
        "source": "Unmodified OriginalPython/core/transits.py; Swiss data 2.10.03. Negative/positive signed references and exact sign boundaries. Synthetic inputs only.",
        "cases": cases,
    }


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true", help="Compare existing fixture; do not write")
    args = parser.parse_args()
    payload = (json.dumps(generate(), ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    if args.check:
        if not args.output.is_file() or args.output.read_bytes() != payload:
            raise SystemExit("Transit fixture differs from the independently regenerated Python oracle")
        print("PASS: all65 transit fixtures regenerated byte for byte; no files changed")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(payload)
        print(f"Wrote65 transit cases to {args.output}")


if __name__ == "__main__":
    main()
